// Build-time: flatten glyph outlines of the light-written words into polylines (stroke playback) -> v2/core/glyphs.js
// usage: node v2/tools/glyphs.js <dir with ttf files>   (ttf made from visual/fonts/*.woff2 with fontTools)
// Copied from out/lookdev/research/tools/glyphs.js; v2 writes "unclench." (Fraunces 400 italic) and "free." (900 italic).
const path = require('path'), fs = require('fs');
const opentype = require(path.resolve(__dirname, 'opentype.min.js'));
const FT = process.argv[2] || '/tmp/v2fonts';
const jobs = [
  ['unclench', 'fraunces-latin-400-italic.ttf', 'unclench.', 150],
  ['free', 'fraunces-latin-900-italic.ttf', 'free.', 240],
];
function flatten(cmds) {
  const contours = []; let cur = null, px = 0, py = 0;
  const push = (x, y) => { cur.push([+x.toFixed(1), +y.toFixed(1)]); px = x; py = y; };
  for (const c of cmds) {
    if (c.type === 'M') { cur = []; contours.push(cur); push(c.x, c.y); }
    else if (c.type === 'L') push(c.x, c.y);
    else if (c.type === 'Q') { const n = Math.max(2, Math.ceil(Math.hypot(c.x - px, c.y - py) / 6)); const x0 = px, y0 = py; for (let i = 1; i <= n; i++) { const t = i / n, u = 1 - t; push(u * u * x0 + 2 * u * t * c.x1 + t * t * c.x, u * u * y0 + 2 * u * t * c.y1 + t * t * c.y); } }
    else if (c.type === 'C') { const n = Math.max(3, Math.ceil(Math.hypot(c.x - px, c.y - py) / 6)); const x0 = px, y0 = py; for (let i = 1; i <= n; i++) { const t = i / n, u = 1 - t; push(u * u * u * x0 + 3 * u * u * t * c.x1 + 3 * u * t * t * c.x2 + t * t * t * c.x, u * u * u * y0 + 3 * u * u * t * c.y1 + 3 * u * t * t * c.y2 + t * t * t * c.y); } }
    else if (c.type === 'Z') { if (cur && cur.length) cur.push(cur[0].slice()); }
  }
  return contours.filter(c => c.length > 1);
}
const out = {};
for (const [key, file, text, size] of jobs) {
  const font = opentype.loadSync(path.join(FT, file));
  const p = font.getPath(text, 0, 0, size);
  const bb = p.getBoundingBox();
  const contours = flatten(p.commands);
  contours.sort((a, b) => Math.min(...a.map(q => q[0])) - Math.min(...b.map(q => q[0])));    // writing order: left to right
  let total = 0; const cs = contours.map(pts => { let L = 0; for (let i = 1; i < pts.length; i++) L += Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]); total += L; return { pts, L: +L.toFixed(1) }; });
  out[key] = { text, size, bbox: [bb.x1, bb.y1, bb.x2, bb.y2].map(v => +v.toFixed(1)), total: +total.toFixed(1), contours: cs };
  console.log(key, contours.length, 'contours, length', total.toFixed(0));
}
fs.writeFileSync(path.resolve(__dirname, '../core/glyphs.js'), '// generated by v2/tools/glyphs.js: glyph outlines for light-writing (V2.type.glyphWrite)\nwindow.V2 = window.V2 || {}; V2.GLYPHS = ' + JSON.stringify(out) + ';\n');
